-- Supabase SQL Editor: pilot tables for the IT checklist app.
-- WARNING: These policies are permissive for testing only. Get IT/security approval.
-- Before production, require staff authentication and restrict access to authorized users.

create table if not exists public.it_daily_checks (
 id bigint generated by default as identity primary key,
 check_date date not null default current_date,
 staff_name text not null default '',
 shift text not null default '',
 checks jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
create table if not exists public.it_issues (
 id bigint generated by default as identity primary key,
 report_date date not null default current_date,
 reported_by text not null,
 system text not null,
 priority text not null default 'Medium',
 description text not null,
 action_taken text not null default '',
 status text not null default 'Open',
 assigned_to text not null default '',
 created_at timestamptz not null default now()
);
alter table public.it_daily_checks enable row level security;
alter table public.it_issues enable row level security;
create policy "pilot read checks" on public.it_daily_checks for select using (true);
create policy "pilot insert checks" on public.it_daily_checks for insert with check (true);
create policy "pilot read issues" on public.it_issues for select using (true);
create policy "pilot insert issues" on public.it_issues for insert with check (true);
create policy "pilot update issues" on public.it_issues for update using (true) with check (true);
